<?php

use App\Http\Controllers\AreaDashboardController;
use App\Http\Controllers\AuthController;
use App\Http\Controllers\BoqController;
use App\Http\Controllers\BranchDashboardController;
use App\Http\Controllers\BranchMappingController;
use App\Http\Controllers\BranchProgressController;
use App\Http\Controllers\DashboardExportController;
use App\Http\Controllers\MasterDataController;
use App\Http\Controllers\MaterialReportController;
use App\Http\Controllers\PriorityOrderController;
use App\Http\Controllers\RevenueOverviewController;
use App\Http\Controllers\SyncController;
use App\Http\Controllers\TelegramMaterialWebhookController;
use App\Http\Controllers\UserManagementController;
use App\Http\Controllers\WorkOrderController;
use App\Http\Controllers\WorkOrderDeviceController;
use App\Http\Controllers\WorkOrderImportController;
use App\Http\Controllers\WorkOrderKmlController;
use App\Http\Middleware\ActiveUser;
use Illuminate\Support\Facades\Route;

Route::get('/', fn () => redirect()->route(! auth()->check() ? 'login' : (auth()->user()->role->areaScope() ? 'area.dashboard' : 'branch.dashboard')));
Route::post('/api/telegram/material/webhook', TelegramMaterialWebhookController::class)->middleware('throttle:120,1')->name('telegram.material.webhook');
Route::middleware('guest')->group(function () {
    Route::view('/login', 'auth.login')->name('login');
    Route::post('/login', [AuthController::class, 'login'])->middleware('throttle:10,1');
});
Route::middleware(['auth', ActiveUser::class])->group(function () {
    Route::prefix('master-data')->name('master-data.')->middleware('can:manage-master-data')->group(function () {
        Route::get('/', fn () => redirect()->route('master-data.index', 'regions'));
        Route::get('/{masterType}', [MasterDataController::class, 'index'])->name('index');
        Route::get('/{masterType}/create', [MasterDataController::class, 'create'])->name('create');
        Route::post('/{masterType}', [MasterDataController::class, 'store'])->name('store');
        Route::get('/{masterType}/{record}/edit', [MasterDataController::class, 'edit'])->whereNumber('record')->name('edit');
        Route::put('/{masterType}/{record}', [MasterDataController::class, 'update'])->whereNumber('record')->name('update');
        Route::get('/{masterType}/{record}/delete', [MasterDataController::class, 'confirmDelete'])->whereNumber('record')->name('confirm-delete');
        Route::delete('/{masterType}/{record}', [MasterDataController::class, 'destroy'])->whereNumber('record')->name('destroy');
    });
    Route::get('/dashboard', [AreaDashboardController::class, 'index'])->middleware('can:area-dashboard')->name('area.dashboard');
    Route::get('/dashboard/exports/{table}', [DashboardExportController::class, 'table'])->middleware(['can:area-dashboard', 'throttle:20,1'])->name('area.dashboard.export');
    Route::get('/branch/dashboard/exports/{table}', [DashboardExportController::class, 'table'])->middleware('throttle:20,1')->name('branch.dashboard.export');
    Route::get('/dashboard/orders/export', [DashboardExportController::class, 'orders'])->middleware('throttle:20,1')->name('dashboard.orders.export');
    Route::get('/revenue', [RevenueOverviewController::class, 'index'])->middleware('can:revenue-overview')->name('revenue.index');
    Route::get('/branch/dashboard', [BranchDashboardController::class, 'index'])->name('branch.dashboard');
    Route::get('/branch/material', fn () => redirect()->route('materials.index'))->name('branch.material');
    Route::get('/materials', [MaterialReportController::class, 'index'])->name('materials.index');
    Route::get('/materials/template', [MaterialReportController::class, 'template'])->name('materials.template');
    Route::get('/materials/template/download', [MaterialReportController::class, 'downloadTemplate'])->name('materials.template.download');
    Route::get('/materials/{materialReport}', [MaterialReportController::class, 'show'])->name('materials.show');
    Route::post('/issues/{issue}/notes', [BranchProgressController::class, 'addIssueNote'])->name('issues.notes');
    Route::resource('users', UserManagementController::class)->only(['index', 'create', 'store', 'edit', 'update'])->middleware('can:administer');
    Route::view('/logout/confirm', 'auth.logout-confirm')->name('logout.confirm');
    Route::post('/logout', [AuthController::class, 'logout'])->name('logout');
    Route::get('/work-orders', [WorkOrderController::class, 'index'])->name('work-orders.index');
    Route::get('/priority-orders', [PriorityOrderController::class, 'index'])->middleware('can:priority-orders')->name('priorities.index');
    Route::post('/work-orders/{workOrder}/priority', [PriorityOrderController::class, 'store'])->name('priorities.store');
    Route::delete('/work-orders/{workOrder}/priority', [PriorityOrderController::class, 'destroy'])->name('priorities.destroy');
    Route::get('/work-orders/{workOrder}/boq/upload', [BoqController::class, 'create'])->name('boqs.create');
    Route::post('/work-orders/{workOrder}/boq', [BoqController::class, 'store'])->middleware('throttle:6,1')->name('boqs.store');
    Route::get('/work-orders/{workOrder}/boq', [BoqController::class, 'show'])->name('boqs.show');
    Route::get('/work-orders/{workOrder}/boq/template', [BoqController::class, 'template'])->name('boqs.template');
    Route::get('/work-orders/{workOrder}/boq/download', [BoqController::class, 'download'])->name('boqs.download');
    Route::get('/work-orders/{workOrder}/kml', [WorkOrderKmlController::class, 'show'])->name('work-orders.kml.show');
    Route::post('/work-orders/{workOrder}/kml', [WorkOrderKmlController::class, 'store'])->middleware('throttle:6,1')->name('work-orders.kml.store');
    Route::get('/work-orders/{workOrder}/kml/data', [WorkOrderKmlController::class, 'data'])->name('work-orders.kml.data');
    Route::get('/work-orders/{workOrder}/kml/download', [WorkOrderKmlController::class, 'download'])->name('work-orders.kml.download');
    Route::get('/work-orders/{workOrder}', [WorkOrderController::class, 'show'])->name('work-orders.show');
    Route::get('/work-orders/{workOrder}/actions/{mode}', [WorkOrderController::class, 'editAction'])->whereIn('mode', ['progress', 'issue', 'close'])->name('work-orders.action.edit');
    Route::patch('/work-orders/{workOrder}/actions/{mode}', [BranchProgressController::class, 'updateAction'])->whereIn('mode', ['progress', 'issue', 'close'])->name('work-orders.action.update');
    Route::patch('/work-orders/{workOrder}/devices', [WorkOrderDeviceController::class, 'update'])->name('work-orders.devices');
    Route::patch('/work-orders/{workOrder}/progress', [BranchProgressController::class, 'update'])->name('work-orders.progress');
    Route::post('/work-orders/{workOrder}/issues', [BranchProgressController::class, 'storeIssue'])->name('work-orders.issues');
    Route::patch('/issues/{issue}/resolve', [BranchProgressController::class, 'resolveIssue'])->name('issues.resolve');
    Route::get('/sync', [SyncController::class, 'index'])->name('sync.index');
    Route::get('/sync/history', [SyncController::class, 'history'])->name('sync.history');
    Route::post('/imports/excel', [WorkOrderImportController::class, 'upload'])->middleware('throttle:6,1')->name('imports.upload');
    Route::get('/imports/{syncJob}/mapping', [WorkOrderImportController::class, 'mapping'])->name('imports.mapping');
    Route::post('/imports/{syncJob}/preview', [WorkOrderImportController::class, 'preview'])->middleware('throttle:6,1')->name('imports.preview');
    Route::post('/sync/bima/preview', [SyncController::class, 'preview'])->middleware('throttle:6,1')->name('sync.preview');
    Route::get('/sync/jobs/{syncJob}', [SyncController::class, 'show'])->name('sync.show');
    Route::post('/sync/jobs/{syncJob}/commit', [SyncController::class, 'commit'])->name('sync.commit');
    Route::post('/sync/jobs/{syncJob}/retry', [SyncController::class, 'retry'])->middleware('throttle:6,1')->name('sync.retry');
    Route::get('/sync/jobs/{syncJob}/exceptions', [SyncController::class, 'errors'])->name('sync.errors');
    Route::get('/branch-mappings', [BranchMappingController::class, 'index'])->name('mappings.index');
    Route::post('/branches', [BranchMappingController::class, 'storeBranch'])->name('branches.store');
    Route::post('/branch-mappings', [BranchMappingController::class, 'store'])->name('mappings.store');
});
